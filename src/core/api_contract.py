"""Contrato de la API: la fuente es Python, el contrato es un artefacto.

La UI hablaba con 138 rutas REST escribiendo strings a mano: si el backend
renombraba una ruta o dejaba de devolver una clave, TypeScript no decía nada y
el error aparecía en runtime como `undefined`. Este módulo lee `server.py` con
`ast` (no con regex, para no confundir un comentario con una ruta) y produce:

- la lista de rutas con método, path params, query params, claves de body que el
  handler realmente lee y claves del dict que devuelve;
- un `.ts` generado que la UI importa, con `findApiRoute()` para validar una
  llamada antes de hacerla;
- una versión (hash) del contrato, para que un cliente sepa contra qué habla.

Lo que NO hace, a propósito: no inventa tipos de respuesta. Los handlers
devuelven dicts, así que la forma real es "estas claves aparecen en el return".
Tipar de verdad requiere modelos Pydantic en cada handler, y eso es un cambio
por ruta que conviene hacer con tests al lado, no de golpe y por script.

Uso:
    .venv-ft314\\Scripts\\python.exe scripts\\gen_api_contract.py
    .venv-ft314\\Scripts\\python.exe scripts\\gen_api_contract.py --check
"""
from __future__ import annotations

import ast
import hashlib
import json
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, Iterable, List, Sequence, Tuple

SERVER_PATH = Path(__file__).resolve().parents[1] / "api" / "server.py"
CONTRACT_PATH = Path(__file__).resolve().parents[2] / "ui" / "src" / "lib" / "api-contract.generated.ts"

HTTP_METHODS = {"get", "post", "put", "patch", "delete"}
# Args que nunca son parámetros del request.
_NOT_PARAMS = {"self", "request", "call_next", "background"}

_HEADER = (
    "// GENERATED by scripts/gen_api_contract.py from src/api/server.py — DO NOT EDIT.\n"
    "// Regenerar: .venv-ft314\\Scripts\\python.exe scripts\\gen_api_contract.py\n"
    "// tests/test_api_contract.py falla cuando este archivo quedó viejo.\n"
)


@dataclass
class Route:
    method: str
    path: str
    handler: str
    path_params: List[str] = field(default_factory=list)
    query_params: List[str] = field(default_factory=list)
    body: List[str] = field(default_factory=list)
    response: List[str] = field(default_factory=list)
    stream: bool = False
    body_open: bool = False

    def to_dict(self) -> Dict[str, Any]:
        return {
            "method": self.method.upper(),
            "path": self.path,
            "handler": self.handler,
            "pathParams": self.path_params,
            "query": self.query_params,
            "body": self.body,
            "bodyOpen": self.body_open,
            "response": self.response,
            "stream": self.stream,
        }

    def fingerprint(self) -> str:
        return json.dumps(self.to_dict(), sort_keys=True, ensure_ascii=False)


def _path_params(path: str) -> List[str]:
    return re.findall(r"\{([a-zA-Z_][a-zA-Z0-9_]*)(?::[^}]+)?\}", path)


def _str_keys(node: ast.AST, var: str) -> List[str]:
    """Claves de `var.get("x")` y `var["x"]` dentro de un nodo."""
    keys: List[str] = []
    for sub in ast.walk(node):
        if isinstance(sub, ast.Call) and isinstance(sub.func, ast.Attribute):
            if sub.func.attr == "get" and isinstance(sub.func.value, ast.Name) and sub.func.value.id == var:
                if sub.args and isinstance(sub.args[0], ast.Constant) and isinstance(sub.args[0].value, str):
                    keys.append(sub.args[0].value)
        elif isinstance(sub, ast.Subscript) and isinstance(sub.value, ast.Name) and sub.value.id == var:
            sl = sub.slice
            if isinstance(sl, ast.Constant) and isinstance(sl.value, str):
                keys.append(sl.value)
    return keys


def _returned_keys(node: ast.AST) -> List[str]:
    keys: List[str] = []
    for sub in ast.walk(node):
        if isinstance(sub, ast.Return) and isinstance(sub.value, ast.Dict):
            for k in sub.value.keys:
                if isinstance(k, ast.Constant) and isinstance(k.value, str):
                    keys.append(k.value)
    return keys


def _is_stream(node: ast.AST) -> bool:
    src = ast.unparse(node)
    if any(tok in src for tok in ("StreamingResponse", "EventSourceResponse", "text/event-stream")):
        return True
    # Handlers que delegan en un helper propio (`_sse_stream_response(...)`).
    return re.search(r"\b\w*stream_response\s*\(", src) is not None


def extract_routes(source: str) -> List[Route]:
    """Rutas declaradas con `@app.<metodo>("/path")` en el fuente dado."""
    tree = ast.parse(source)
    out: List[Route] = []
    for node in tree.body:
        if not isinstance(node, (ast.AsyncFunctionDef, ast.FunctionDef)):
            continue
        for dec in node.decorator_list:
            if not isinstance(dec, ast.Call):
                continue
            fn = dec.func
            if not isinstance(fn, ast.Attribute) or fn.attr not in HTTP_METHODS:
                continue
            if not isinstance(fn.value, ast.Name) or fn.value.id != "app":
                continue
            if not (dec.args and isinstance(dec.args[0], ast.Constant) and isinstance(dec.args[0].value, str)):
                continue
            path = dec.args[0].value
            pp = _path_params(path)
            query: List[str] = []
            for a in node.args.args:
                if a.arg in _NOT_PARAMS or a.arg in pp:
                    continue
                query.append(a.arg)
            uses_body = "_json_body" in ast.unparse(node)
            body_keys = sorted(set(_str_keys(node, "body"))) if uses_body else []
            route = Route(
                method=fn.attr.upper(),
                path=path,
                handler=node.name,
                path_params=pp,
                query_params=query,
                body=body_keys,
                response=sorted(set(_returned_keys(node))),
                stream=_is_stream(node),
                # Un handler que recibe el body entero (patch parcial) no tiene
                # claves fijas: la UI puede mandar cualquiera.
                body_open=bool(uses_body and not body_keys),
            )
            out.append(route)
    out.sort(key=lambda r: (r.path, r.method))
    return out


def contract_version(routes: Sequence[Route]) -> str:
    blob = "\n".join(r.fingerprint() for r in routes).encode("utf-8")
    return hashlib.sha256(blob).hexdigest()[:12]


def render_typescript(routes: Sequence[Route]) -> str:
    version = contract_version(routes)
    lines: List[str] = [_HEADER, ""]
    lines.append("/** Versión del contrato: hash del contenido. Cambia si cambia una ruta. */")
    lines.append(f'export const API_CONTRACT_VERSION = "{version}"')
    lines.append("")
    lines.append("export type HttpMethod = 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE'")
    lines.append("")
    lines.append("export interface ApiRoute {")
    lines.append("  method: HttpMethod")
    lines.append("  path: string")
    lines.append("  handler: string")
    lines.append("  pathParams: readonly string[]")
    lines.append("  query: readonly string[]")
    lines.append("  /** Claves que el handler lee del body JSON (`body.get(...)`). */")
    lines.append("  body: readonly string[]")
    lines.append("  /** true = el handler acepta el body completo (patch parcial, sin claves fijas). */")
    lines.append("  bodyOpen: boolean")
    lines.append("  /** Claves que aparecen en el dict devuelto (no es un tipo completo). */")
    lines.append("  response: readonly string[]")
    lines.append("  stream: boolean")
    lines.append("}")
    lines.append("")
    lines.append("export const API_ROUTES: readonly ApiRoute[] = [")
    for r in routes:
        d = r.to_dict()
        parts = [
            f'method: "{d["method"]}"',
            f'path: "{d["path"]}"',
            f'handler: "{d["handler"]}"',
            "pathParams: " + json.dumps(d["pathParams"]).replace('"', "'"),
            "query: " + json.dumps(d["query"]).replace('"', "'"),
            "body: " + json.dumps(d["body"]).replace('"', "'"),
            f'bodyOpen: {"true" if d["bodyOpen"] else "false"}',
            "response: " + json.dumps(d["response"]).replace('"', "'"),
            f'stream: {"true" if d["stream"] else "false"}',
        ]
        lines.append("  { " + ", ".join(parts) + " },")
    lines.append("]")
    lines.append("")
    lines.append("/** Todos los paths declarados (sin método), para chequeos rápidos. */")
    paths = sorted({r.path for r in routes})
    lines.append("export const API_PATHS: readonly string[] = [")
    for p in paths:
        lines.append(f"  '{p}',")
    lines.append("]")
    lines.append("")
    lines.append("const _templateCache = new Map<string, RegExp>()")
    lines.append("")
    lines.append("/** Convierte `/a/{id}/b` en una regex que matchea un path concreto. */")
    lines.append("function _template(path: string): RegExp {")
    lines.append("  const hit = _templateCache.get(path)")
    lines.append("  if (hit) return hit")
    lines.append("  const src =")
    lines.append("    '^' +")
    lines.append("    path")
    lines.append("      .split('/')")
    lines.append("      .map((seg) => (/^\\{[^}]+\\}$/.test(seg) ? '[^/]+' : seg.replace(/[.*+?^${}()|[\\]\\\\]/g, '\\\\$&')))")
    lines.append("      .join('/') +")
    lines.append("    '$'")
    lines.append("  const re = new RegExp(src)")
    lines.append("  _templateCache.set(path, re)")
    lines.append("  return re")
    lines.append("}")
    lines.append("")
    lines.append("/**")
    lines.append(" * Busca la ruta declarada que corresponde a (método, path concreto).")
    lines.append(" * Devuelve undefined si el backend no expone esa ruta: sirve para fallar")
    lines.append(" * temprano en tests en vez de recibir un 404 en runtime.")
    lines.append(" */")
    lines.append("export function findApiRoute(method: string, path: string): ApiRoute | undefined {")
    lines.append("  const sinQuery = path.split('?')[0]")
    lines.append("  const m = method.toUpperCase()")
    lines.append("  return API_ROUTES.find((r) => r.method === m && _template(r.path).test(sinQuery))")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def render(server: Path = SERVER_PATH) -> str:
    return render_typescript(extract_routes(server.read_text(encoding="utf-8")))


def normalizar_path_de_ui(raw: str) -> str:
    """`/api/sessions/${id}/fork?x=1` -> `/api/sessions/{}/fork`.

    Un `${...}` que no ocupa un segmento entero (p. ej. `/api/x${q}`, donde la
    variable trae el `?query`) corta el path: no es parte de la ruta.
    """
    p = raw.split("?")[0]
    salida: List[str] = []
    i = 0
    while i < len(p):
        if p.startswith("${", i):
            fin = p.find("}", i)
            if fin == -1:
                break
            es_segmento = (i == 0 or p[i - 1] == "/") and (fin + 1 == len(p) or p[fin + 1] == "/")
            if not es_segmento:
                break
            salida.append("{}")
            i = fin + 1
            continue
        salida.append(p[i])
        i += 1
    return "".join(salida)


def normalizar_path_de_contrato(raw: str) -> str:
    p = raw.split("?")[0]
    p = re.sub(r"\{[^}]*\}", "{}", p)
    return p


def paths_usados_por_la_ui(*archivos: Path) -> List[Tuple[str, str]]:
    """(archivo, path) de cada `/api/...` literal o plantilla que la UI pide."""
    out: List[Tuple[str, str]] = []
    patron = re.compile(r"""["'`](/api/[^"'`\s]*)["'`]""")
    for f in archivos:
        if not f.is_file() or f.name.endswith(".generated.ts"):
            continue
        for m in patron.finditer(f.read_text(encoding="utf-8", errors="replace")):
            raw = m.group(1)
            # `/api/` suelto es un prefijo (base de URL, proxy), no un request.
            if raw.rstrip("/") == "/api":
                continue
            out.append((f.name, raw))
    return out


def rutas_no_declaradas(declaradas: Iterable[str], usadas: Iterable[Tuple[str, str]]) -> List[str]:
    sets = {normalizar_path_de_contrato(p) for p in declaradas}
    faltan: List[str] = []
    for _archivo, raw in usadas:
        norm = normalizar_path_de_ui(raw)
        if norm not in sets:
            faltan.append(raw)
    return sorted(set(faltan))
